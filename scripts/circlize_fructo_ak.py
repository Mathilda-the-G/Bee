from pathlib import Path
import numpy as np
import pandas as pd
from pycirclize import Circos
from pycirclize.parser import Genbank
from matplotlib.patches import Patch
 
# ---- settings ----
REPO = Path(__file__).resolve().parent.parent      # the Bee folder
# Same approach as circlize.py, but the core is defined over 8 Fructobacillus + 5 A. kunkeei (13/13)
PROKKA_FRUCTO = REPO / "results" / "prokka" / "fructo_reoriented"   # Prokka on dnaapler-reoriented Fructobacillus
PROKKA_AK = REPO / "results" / "prokka" / "a_kunkeei"               # Prokka on A. kunkeei (already start at dnaA)
OF_FRUCTO_AK = REPO / "results" / "orthofinder" / "of_fructo_ak" / "Orthogroups"  # 8 Fructobacillus + 5 A. kunkeei
# 8 Fructobacillus + 5 A. kunkeei, strict core (13/13); plots + summary.tsv
OUT = REPO / "results" / "pyCirclize" / "fructobacillus_a_kunkeei_core_13of13"
OUT.mkdir(parents=True, exist_ok=True)
 
COLORS = {
    "core (Fructobacillus + A. kunkeei)": "#c0392b",   # red: in all 13 genomes
    "accessory":                          "#27ae60",   # green: in 2-12 of the 13 genomes
    "unique":                             "#f39c12",   # orange: in 1 genome (or unassigned)
}
 
 
# ---- reading files ----
# Reads the .gff generated by Prokka.
# Creates a table with one row per gene containing
# sequence ID, start and end, strand (+ or -), locus tag and gene name.
def read_gff(path):
    """CDS positions and sequence sizes from a Prokka GFF."""
    sizes, genes = {}, []
    with open(path) as fh:
        for line in fh:
            if line.startswith("##FASTA"):        # so we don't read the whole sequence
                break
            if line.startswith("##sequence-region"):   # used later to pick the longest sequence (chromosome)
                _, seqid, _, end = line.split()
                sizes[seqid] = int(end)
                continue
            if line.startswith("#"):              # skip other header lines
                continue
            f = line.rstrip("\n").split("\t")
            if f[2] != "CDS":                     # only keep CDS genes
                continue
            attrs = dict(x.split("=", 1) for x in f[8].split(";"))
            genes.append({"seqid": f[0], "start": int(f[3]), "end": int(f[4]),
                          "strand": f[6], "locus_tag": attrs["locus_tag"],
                          "gene": attrs.get("gene", "")})
    return sizes, pd.DataFrame(genes)
 
 
# Orthogroups.tsv has one cell per genome and orthogroup, holding that genome's
# genes in the group as Prokka locus tags, e.g. "MFOPEDCC_00169, MFOPEDCC_01022"
# (several genes = paralogs). An empty cell means the genome lacks the orthogroup.
# Returns the cell as a list of locus tags, or an empty list.
def genes_in(cell):
    """Turn an Orthogroups.tsv cell ('A_001, A_002') into a list of gene IDs."""
    return [] if pd.isna(cell) else cell.split(", ")
 
 
# ---- gene categories (done once, for all genomes) ----
og_fructo_ak = pd.read_csv(OF_FRUCTO_AK / "Orthogroups.tsv", sep="\t", index_col=0) #Fructobacillus + A. kunkeei run
unassigned = pd.read_csv(OF_FRUCTO_AK / "Orthogroups_UnassignedGenes.tsv", sep="\t", index_col=0) #holds genes OrthoFinder couldn’t put in any group
GENOMES = list(og_fructo_ak.columns)                   # 8 Fructobacillus (GCF_) + 5 A. kunkeei (GCA_)

#Core, accessory, unique thresholds 
category = {}
for _, row in og_fructo_ak.iterrows():
    n = sum(len(genes_in(c)) > 0 for c in row) #Count how many genomes have at least one gene in it
    cat = "core" if n == len(GENOMES) else "accessory" if n >= 2 else "unique"
    for genome in GENOMES:
        for g in genes_in(row[genome]):
            category[g] = cat #Assign category (core, accessory or unique)      
for genome in GENOMES:
    for g in unassigned[genome].dropna():
        category[g] = "unique" #Unassinged genes added as unique

#Rename "core" to the label used in the plot legend
def final_category(gene):
    cat = category.get(gene, "unique")
    return "core (Fructobacillus + A. kunkeei)" if cat == "core" else cat
 
 
# ---- short names from the metadata ----
#links each accession to a short strain name (e.g. GCF_058511985.1 -> ESL1096) and to the species name
#(e.g. "Fructobacillus sp."), used in the plot titles and file names.
meta = pd.read_csv(REPO / "metadata" / "genome_metadata.tsv", sep="\t")
NAMES = {acc: strain.split()[-1].replace("_", "")
         for acc, strain in zip(meta.accession, meta.species_strain)}
SPECIES = {acc: " ".join(strain.split()[:2])
           for acc, strain in zip(meta.accession, meta.species_strain)}
# A. kunkeei names come from the NCBI metadata table
ak_meta = pd.read_csv(REPO / "metadata" / "raw" / "a_kunkeei_metadata.tsv", sep="\t")
for acc, org, strain in zip(ak_meta["Assembly Accession"], ak_meta["Organism Name"],
                            ak_meta["Organism Infraspecific Names Strain"]):
    NAMES[acc] = str(strain)
    SPECIES[acc] = org

def italic_species(species):
    """Species name in italics for the plot title ('sp.' stays upright)."""
    genus, epithet = species.split()
    if epithet == "sp.":
        return rf"$\it{{{genus}}}$ sp."
    return rf"$\it{{{genus}\ {epithet}}}$"
 
# ---- one plot per genome ----
def plot_genome(genome):
    name = NAMES.get(genome, genome)
    species = SPECIES.get(genome, "")
    prokka = PROKKA_FRUCTO if genome.startswith("GCF") else PROKKA_AK
    gff = prokka / f"{genome}_annotated" / f"{genome}.gff"
 
    sizes, genes = read_gff(gff)
    chrom = max(sizes, key=sizes.get)              # longest sequence = chromosome
    size = sizes[chrom]
    genes = genes[genes.seqid == chrom].copy()
    genes["category"] = genes.locus_tag.map(final_category)
 
    # GC skew in sliding windows, calculated by pyCirclize from the Prokka GenBank file
    gbk = Genbank(prokka / f"{genome}_annotated" / f"{genome}.gbk")
    pos, skew = gbk.calc_gc_skew(seq=gbk.get_seqid2seq()[chrom])
    cum_skew = np.cumsum(skew)
    ori = 0                                        # all genomes start at dnaA
    ter = pos[np.argmax(cum_skew)]                 # ter = maximum of the cumulative GC skew
    skew_min = pos[np.argmin(cum_skew)]            # check: should be close to 0 (or to the genome size)
    print(f"{name}: ter {ter:,.0f}, cumulative skew minimum at {skew_min:,.0f} (should be ~0 or ~{size:,})")
 
    # genomes start at dnaA/ori, so position 0 is already at the top (no rotation needed)
    circos = Circos({chrom: size})
    sector = circos.sectors[0]

    #Gray scale ring, label every 250 kb
    axis = sector.add_track((98, 100))
    axis.axis(fc="lightgrey", ec="none")
    axis.xticks_by_interval(250_000, label_formatter=lambda v: f"{v/1e6:.2f} Mb")

    #+ strand outside, - strand inside
    fwd = sector.add_track((88, 96))
    rev = sector.add_track((79, 87))
    for g in genes.itertuples():
        track = fwd if g.strand == "+" else rev
        track.rect(g.start - 1, g.end, fc=COLORS[g.category], lw=0)

    #GC skew ring
    lim = np.abs(skew).max()
    sk = sector.add_track((62, 76))
    sk.fill_between(pos, np.where(skew > 0, skew, 0), vmin=-lim, vmax=lim, color="#7d3c98", lw=0)
    sk.fill_between(pos, np.where(skew < 0, skew, 0), vmin=-lim, vmax=lim, color="#d4ac0d", lw=0)

    #Cumulative skew, black line
    cs = sector.add_track((46, 60))
    cs.line(pos, cum_skew, vmin=cum_skew.min(), vmax=cum_skew.max(), color="black", lw=1)

    #Marks ori and ter
    for label, x in (("ori", ori), ("ter", ter)):
        sector.rect(max(0, x - 2000), min(size, x + 2000), r_lim=(46, 100), fc="black", lw=0)
        sector.text(label, x=x, r=107, size=10, fontweight="bold")

    #Puts the name and size in the centre, turns the circle into a matplotlib figure, adds the colour legend and saves the PNG
    circos.text(f"{italic_species(species)}\n{name}\n{size/1e6:.2f} Mb", size=12)
    fig = circos.plotfig()
    handles = [Patch(color=c, label=k) for k, c in COLORS.items()]
    fig.legend(handles=handles, loc="lower right", fontsize=8, frameon=False)
    fig.savefig(OUT / f"{species.replace('.', '').replace(' ', '_')}_{name}_circos.png", dpi=200)

    #counts the genes per category and returns one row of information for this genome
    counts = genes.category.value_counts().to_dict()
    return {"genome": name, "species": species, "accession": genome, "size_bp": size,
            "ter": round(ter), "skew_min": round(skew_min), **counts}
 
 
summary = pd.DataFrame([plot_genome(g) for g in GENOMES]).fillna(0)
cols = [c for c in summary.columns if c not in COLORS] + list(COLORS)   # categories in legend order
summary = summary.reindex(columns=cols, fill_value=0)
summary[list(COLORS)] = summary[list(COLORS)].astype(int)
summary.to_csv(OUT / "summary.tsv", sep="\t", index=False)
print(summary.to_string(index=False))

